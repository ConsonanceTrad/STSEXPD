	private LearnRoomLayouts() {
	}

	private static int[] decode() {
		if (ROWS.length != 48) throw new IllegalStateException("tutorial layout height");
		int[] result = new int[48 * 48];
		for (int y = 0; y < ROWS.length; y++) {
			if (ROWS[y].length() != 48) throw new IllegalStateException("tutorial layout width at row " + y);
			for (int x = 0; x < 48; x++) result[x + y * 48] = terrain(ROWS[y].charAt(x));
		}
		return result;
	}

	private static int terrain(char code) {
		switch (code) {
			case '#': return Terrain.WALL;
			case '.': return Terrain.EMPTY;
			case 't': return Terrain.TENT;
			case 'd': return Terrain.DOOR;
			case 'l': return Terrain.LOCKED_DOOR;
			case 'h': return Terrain.SECRET_DOOR;
			case 'n': return Terrain.GROUND_A;
			case 'm': return Terrain.EMPTY_SP;
			case 'p': return Terrain.SECRET_TRAP;
			case '~': return Terrain.WATER;
			case 'a': return Terrain.GLASS_WALL;
			case 'g': return Terrain.GRASS;
			case 'G': return Terrain.HIGH_GRASS;
			case 'q': return Terrain.OLD_HIGH_GRASS;
			case ',': return Terrain.EMPTY_DECO;
			case 'k': return Terrain.BOOKSHELF;
			case 's': return Terrain.STATUE;
			default: throw new IllegalArgumentException("unknown tutorial terrain: " + code);
		}
	}
