package com.shatteredpixel.shatteredpixeldungeon.levels.features;

import com.shatteredpixel.shatteredpixeldungeon.Dungeon;
import com.shatteredpixel.shatteredpixeldungeon.actors.Char;
import com.shatteredpixel.shatteredpixeldungeon.actors.buffs.Buff;
import com.shatteredpixel.shatteredpixeldungeon.actors.buffs.Dewcharge;
import com.shatteredpixel.shatteredpixeldungeon.actors.hero.Hero;
import com.shatteredpixel.shatteredpixeldungeon.effects.CellEmitter;
import com.shatteredpixel.shatteredpixeldungeon.effects.particles.ElmoParticle;
import com.shatteredpixel.shatteredpixeldungeon.levels.Level;
import com.shatteredpixel.shatteredpixeldungeon.levels.Terrain;
import com.shatteredpixel.shatteredpixeldungeon.messages.Messages;
import com.shatteredpixel.shatteredpixeldungeon.scenes.GameScene;
import com.shatteredpixel.shatteredpixeldungeon.utils.GLog;

public final class DewBlessRoom {

	private DewBlessRoom() {
	}

	public static void trample(Level level, int pos, Char ch) {
		CellEmitter.get(pos).burst(ElmoParticle.FACTORY, 6);
		if (ch instanceof Hero) {
			Buff.affect((Hero) ch, Dewcharge.class, 720f);
			GLog.h(Messages.get(DewBlessRoom.class, "order"), level.spsDewPar());
			Level.set(pos, Terrain.GRASS);
			GameScene.updateMap(pos);
		}
		Dungeon.observe();
	}
}
